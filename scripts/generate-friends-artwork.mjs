// Demo-only artwork. One reviewed model drives each scene and expression export.
const artwork = new URL(
  '../playground/src/examples/scenes/artwork/friends-preview/',
  import.meta.url,
);
const source = await readFile(new URL('source/characters.svg', artwork), 'utf8');
const definitions = source.match(/<defs\b[^>]*>([\s\S]*?)<\/defs>/)?.[1];
if (!definitions) throw new Error('The character source must provide one defs block.');
if (/<(?:image|script)\b|(?:href|xlink:href)=["'](?:https?:|data:)/i.test(source)) {
  throw new Error('Character artwork must be self-contained vector paths.');
}
const characters = ['chiikawa', 'hachiware', 'usagi'];
const expressions = ['bright', 'smile', 'surprised'];
const names = { chiikawa: '吉伊', hachiware: '小八', usagi: '乌萨奇' };
const moods = { bright: '自然睁眼', smile: '闭眼笑', surprised: '惊讶' };
for (const character of characters) {
  for (const expression of expressions) {
    if (!new RegExp(`id=["']${character}-${expression}["']`).test(definitions)) {
      throw new Error(`Missing character model: ${character}-${expression}`);
    }
  }
}

if (!/id=["']chiikawa-grip["']/.test(definitions)) {
  throw new Error('Missing shared card-grip model: chiikawa-grip');
}

