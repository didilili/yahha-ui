const outputs = new Map([
  ['friends-hero.svg', hero],
  ['friends-peek.svg', peek],
]);
for (const character of characters) {
  for (const expression of expressions) {
    outputs.set(
      `portraits/${character}-${expression}.svg`,
      svg(
        `${names[character]}：${moods[expression]}。`,
        '-110 -205 220 310',
        `<use href="#${character}-${expression}"/>`,
      ),
    );
  }
}
const config = (await resolveConfig(fileURLToPath(new URL('README.md', artwork)))) ?? {};
let count = 0;
for (const [path, markup] of outputs) {
  const content = await format(markup, { ...config, parser: 'html' });
  const url = new URL(path, artwork);
  if (process.argv.includes('--check')) {
    if ((await readFile(url, 'utf8')) !== content)
      throw new Error(`Generated artwork drift: ${path}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
  count += 1;
}
console.log(
  `${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${count} demo-only SVG files from one character model.`,
);
